"""Порог третьего фильтра должен зависеть от глубины.

Эталон всегда оказывается среди кандидатов: если BM25 его не нашёл,
`filter_by_teacher` вставляет его силой. Значит место эталона после
переранжирования — число от 1 до `depth`, и порог, не меньший глубины,
пропускает всё. Такой фильтр не отбрасывает ничего, стоит час видеокарты
и показывает в отчёте «принято N из N».

Ловушка не теоретическая: в плане урезания глубина снижалась со 100 до 30
при пороге 50 — то есть фильтр выключался, а выглядело это как удешевление.
"""
from __future__ import annotations

import os
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "kaggle"))

import gpu_gen as G  # noqa: E402


def порог(depth: int, keep_top: int | None = None) -> int:
    """Порог, который выберет фильтр, — по той же ветке, что и в нём."""
    return max(1, depth // 2) if keep_top is None else keep_top


@pytest.mark.parametrize("depth,ожидаемый", [(100, 50), (30, 15), (10, 5), (2, 1), (1, 1)])
def test_порог_по_умолчанию_половина_глубины(depth, ожидаемый):
    assert порог(depth) == ожидаемый


@pytest.mark.parametrize("depth", [1, 2, 10, 30, 100])
def test_порог_всегда_строго_меньше_глубины_кроме_вырожденной(depth):
    """Иначе фильтр пропускает всё: место эталона не больше глубины."""
    if depth > 1:
        assert порог(depth) < depth


def test_фильтр_отказывается_работать_вхолостую():
    """Глубина 30 с порогом 50 — та самая ошибка плана. Лучше отказ,
    чем час видеокарты и отчёт «принято 12000 из 12000»."""
    with pytest.raises(ValueError, match="не меньше глубины"):
        G.filter_by_teacher([], [], depth=30, keep_top=50)


def test_отказ_и_при_равенстве():
    with pytest.raises(ValueError, match="не меньше глубины"):
        G.filter_by_teacher([], [], depth=30, keep_top=30)


def test_доля_отсева_при_равномерных_местах():
    """При порогe в половину глубины отсеивается примерно половина —
    это и значит, что фильтр работает, а не только тратит время."""
    depth = 30
    keep = порог(depth)
    места = range(1, depth + 1)
    прошли = [m for m in места if m <= keep]
    assert 0 < len(прошли) < depth
    assert len(прошли) / depth == pytest.approx(0.5, abs=0.02)
