"""Разбор живых вопросов: привязка к акту, чистка пунктов, нумерация.

Все три ошибки здесь тихие. Неверная привязка даёт эталон из чужого акта,
дата вместо пункта — вопрос, который «размечается автоматически» и никогда
ничего не находит, сдвиг нумерации — прежние оценки, привязанные к чужим
текстам.
"""
from __future__ import annotations

from rufin.explanations import (
    act_of,
    assign_ids,
    clean_clauses,
    starts_clause,
)

КОРПУС = {"590-П", "4892-У", "180-И"}


def test_дата_не_считается_номером_пункта():
    assert clean_clauses(["3.1.3", "09.12.2019", "1.1"]) == ["3.1.3", "1.1"]


def test_настоящие_пункты_переживают_чистку():
    assert clean_clauses(["3.7.2.2", "12.5"]) == ["3.7.2.2", "12.5"]


def test_акт_из_заголовка_раздела_имеет_приоритет():
    q = {"acts": ["590-П"], "text": "Согласно 4892-У банк обязан..."}
    assert act_of(q, КОРПУС) == "590-П"


def test_акт_берётся_из_текста_если_в_заголовке_его_нет():
    q = {"acts": [], "text": "В соответствии с пунктом 2.1 Положения № 590-П..."}
    assert act_of(q, КОРПУС) == "590-П"


def test_акт_вне_корпуса_не_привязывается():
    q = {"acts": ["161-ФЗ"], "text": "Согласно Закону № 161-ФЗ..."}
    assert act_of(q, КОРПУС) is None


def test_акт_из_темы_блока_не_используется():
    """Тема названа актом, но вопрос к корпусу не привязывается.

    Правило намеренно узкое: пригодность темы как источника проверить
    не на чем — после чистки от дат у таких вопросов не осталось
    ни одного номера пункта.
    """
    q = {"acts": [], "topic": "Указание Банка России № 590-П", "text": "Как быть?"}
    assert act_of(q, КОРПУС) is None


def test_пункт_ищется_по_началу_строки_а_не_по_вхождению():
    """Перекрёстная ссылка не делает фрагмент эталоном."""
    ссылка = "Резерв формируется в соответствии с пунктом 3.1.3 настоящего Положения."
    начало = "3.1.3. Кредитная организация оценивает риск по ссуде."
    assert not starts_clause(ссылка, "3.1.3")
    assert starts_clause(начало, "3.1.3")


def test_известные_номера_не_сдвигаются():
    известно = {"второй": "exp0001"}
    выдано = assign_ids(["первый", "второй", "третий"], известно)
    assert выдано["второй"] == "exp0001"
    assert выдано["первый"] == "exp0002"
    assert выдано["третий"] == "exp0003"


def test_нумерация_с_нуля_когда_известных_нет():
    выдано = assign_ids(["а", "б"], {})
    assert выдано == {"а": "exp0000", "б": "exp0001"}
