"""Нарезка выпуска «Вестника» на отдельные акты.

Это самое хрупкое место сбора корпуса: ошибка здесь не падает, а тихо
отдаёт акт с чужими приложениями. Проверяется то, что уже один раз ломалось.
"""
from __future__ import annotations

from rufin.vestnik_split import (
    _chrome_lines,
    _find_starts,
    dehyphenate,
    norm_line,
    normalize_number,
)


def test_строка_приводится_к_одному_виду():
    assert norm_line("  ПОЛОЖЕНИЕ   Банка    России  ") == "ПОЛОЖЕНИЕ Банка России"


def test_разные_тире_приводятся_к_дефису():
    assert normalize_number("590–П") == "590-П"
    assert normalize_number("590 — п") == "590-П"


def test_номер_не_превращается_в_no():
    # приводить строку через NFKC нельзя: он делает из «№» строку «No»,
    # и номер перестаёт опознаваться
    assert normalize_number("4-МР") == "4-МР"


def test_перенос_склеивается():
    assert dehyphenate("прово-\nдиться") == "проводиться"


def test_составное_слово_не_склеивается():
    # продолжение с прописной — это не перенос, а следующая строка
    assert dehyphenate("Банка-\nРоссии") == "Банка-\nРоссии"


def test_цепочка_переносов_разбирается():
    assert dehyphenate("кре-\nдит-\nной") == "кредитной"


def _страницы() -> list[list[str]]:
    """Две полосы: настоящий акт и ссылка на чужой, разорванная вёрсткой."""
    return [
        ["ВЕСТНИК БАНКА РОССИИ", "ПОЛОЖЕНИЕ",
         "О порядке формирования резервов", "№ 590-П", "1.1. Текст акта."],
        ["ВЕСТНИК БАНКА РОССИИ", "1.2. Продолжение текста.",
         "Инструкция", "Банка России", "№ 138-И", "приложение настоящего акта"],
    ]


def test_начала_актов_находятся_по_виду_и_номеру():
    starts = _find_starts(_страницы())
    assert [s[2] for s in starts] == ["590-П", "138-И"]
    assert starts[0][3] == "ПОЛОЖЕНИЕ"


def test_название_берется_до_номера():
    assert _find_starts(_страницы())[0][4] == "О порядке формирования резервов"


def test_ссылка_на_чужой_акт_не_открывает_новый():
    # «Инструкция / Банка России / № 138-И» — это ссылка внутри текста,
    # неотличимая от начала акта. Раньше она забирала себе 88 страниц
    # приложений настоящего акта. Спасает сверка с перечнем выпуска.
    starts = _find_starts(_страницы(), expected={"590-П"})
    assert [s[2] for s in starts] == ["590-П"]


def test_один_акт_не_открывается_дважды():
    страницы = [
        ["ПОЛОЖЕНИЕ", "О порядке", "№ 590-П"],
        ["ПОЛОЖЕНИЕ", "О порядке", "№ 590-П"],
    ]
    assert len(_find_starts(страницы)) == 1


def test_вид_документа_с_припиской_опознается():
    страницы = [["УКАЗАНИЕ БАНКА РОССИИ", "О внесении", "№ 1-У"]]
    assert [s[2] for s in _find_starts(страницы)] == ["1-У"]


def test_вид_документа_строчными_опознается():
    страницы = [["Методические рекомендации", "О применении", "№ 4-МР"]]
    assert [s[3] for s in _find_starts(страницы)] == ["МЕТОДИЧЕСКИЕ РЕКОМЕНДАЦИИ"]


def test_вид_без_номера_актом_не_считается():
    assert _find_starts([["ПОЛОЖЕНИЕ", "упомянуто в тексте"]]) == []


def test_колонтитул_находится_по_повторяемости():
    # признак не зависит от вёрстки: она менялась, а повторяемость — нет
    страницы = [["ВЕСТНИК БАНКА РОССИИ", f"текст полосы {i}"] for i in range(4)]
    chrome = _chrome_lines(страницы)
    assert "ВЕСТНИК БАНКА РОССИИ" in chrome
    assert "текст полосы 0" not in chrome


def test_длинная_строка_колонтитулом_не_считается():
    длинная = "а" * 200
    страницы = [[длинная] for _ in range(10)]
    assert длинная not in _chrome_lines(страницы)
