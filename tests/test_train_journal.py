"""Правило приёмки этапа рецепта: объявлено заранее и работает как объявлено.

Зачем на это тест. Правило — единственное место, где решается, что попадёт
в итоговую модель, и подправить его после прогона технически ничего
не стоит. Тест фиксирует его до того, как появились числа: прирост
принимается только если парный перестановочный тест даёт p < 0,05,
а этап матрёшки — если он не ухудшил dev.

Второе, что здесь проверяется: отклонённый этап не становится новым
лучшим. Иначе следующий этап обучался бы поверх состава, который сам
не прошёл, и таблица перестала бы читаться.
"""
from __future__ import annotations

import numpy as np
import pytest

from rufin.metrics import METRICS
from rufin.training.journal import (
    НЕ_УСТАНОВЛЕН,
    ОТКЛОНЁН,
    ПРИНЯТ,
    Journal,
    entry_from_per_query,
    verdict,
)


def поквериные(значения: list[float]) -> tuple[dict, list[str]]:
    """Поквериные значения всех метрик: нас интересует только NDCG@10,
    остальные заполняются тем же, чтобы запись была полной."""
    qids = [f"dv{i:05d}" for i in range(len(значения))]
    return {name: list(значения) for name in METRICS}, qids


def запись(tag: str, stage: str, значения: list[float], **kw):
    pq, qids = поквериные(значения)
    return entry_from_per_query(tag, stage, pq, qids, **kw)


# ---- само правило ----

def test_прирост_с_маленьким_p_принимается():
    assert verdict(0.03, 0.01, 0.05, 0.001) == ПРИНЯТ


def test_прирост_без_свидетельства_не_принимается():
    """Усложнение рецепта без свидетельства выигрыша — это подгонка
    под dev: на тесте оно не воспроизведётся."""
    assert verdict(0.01, -0.02, 0.04, 0.42) == НЕ_УСТАНОВЛЕН


def test_отсутствие_прироста_это_отказ():
    assert verdict(-0.02, -0.05, 0.01, 0.30) == ОТКЛОНЁН
    assert verdict(0.0, -0.03, 0.03, 0.90) == ОТКЛОНЁН


def test_матрёшка_принимается_если_не_навредила():
    """У этапа D задача не качество, а применимость: вектор на 128
    измерений уменьшает индекс втрое. Поэтому довольно того, что dev
    не просел заметно."""
    assert verdict(-0.004, -0.02, 0.01, 0.6, by_applicability=True) == ПРИНЯТ
    assert verdict(-0.05, -0.08, -0.02, 0.001, by_applicability=True) == ОТКЛОНЁН


# ---- журнал ----

def test_первый_этап_сравнивается_с_базовой_линией():
    j = Journal()
    j.add(запись("базовая", "базовая", [0.4] * 50))
    rng = np.random.default_rng(0)
    лучше = [0.4 + 0.1 + float(rng.normal(0, 0.01)) for _ in range(50)]
    e = j.add(запись("a-1ep", "A", лучше))
    assert e.compared_with == "базовая"
    assert e.verdict == ПРИНЯТ
    assert e.diff["mean"] == pytest.approx(0.1, abs=0.01)


def test_отклонённый_этап_не_становится_лучшим():
    j = Journal()
    j.add(запись("базовая", "базовая", [0.4] * 40))
    rng = np.random.default_rng(1)
    j.add(запись("a-1ep", "A", [0.5 + float(rng.normal(0, 0.01)) for _ in range(40)]))
    плохой = j.add(запись("b-neg", "B", [0.45] * 40))
    assert плохой.verdict == ОТКЛОНЁН
    assert j.best().tag == "a-1ep"
    # следующий этап сравнивается с a-1ep, а не с отклонённым b-neg
    rng = np.random.default_rng(2)
    следующий = j.add(запись("c-kl", "C",
                             [0.56 + float(rng.normal(0, 0.01)) for _ in range(40)]))
    assert следующий.compared_with == "a-1ep"


def test_сравнение_парное_и_только_по_общим_вопросам():
    """Разные знаменатели сделали бы разницу бессмысленной."""
    j = Journal()
    j.add(запись("базовая", "базовая", [0.4] * 30))
    e = запись("a-1ep", "A", [0.5] * 20)
    e = j.add(e)
    assert e.diff["запросов"] == 20


def test_повторный_прогон_этапа_заменяет_его_запись():
    """Этап можно переделать, и в таблице он обязан остаться одной строкой:
    запас квоты позволяет переделать любой этап трижды."""
    j = Journal()
    j.add(запись("базовая", "базовая", [0.4] * 30))
    j.add(запись("a-1ep", "A", [0.45] * 30))
    j.add(запись("a-1ep", "A", [0.55] * 30))
    метки = [e.tag for e in j.entries]
    assert метки == ["базовая", "a-1ep"]
    assert j.by_tag("a-1ep").ndcg == pytest.approx(0.55)


def test_таблица_печатает_и_отклонённое(tmp_path):
    """Отклонённый этап — такой же результат, как принятый, и из отчёта
    он не выбрасывается."""
    j = Journal()
    j.add(запись("базовая", "базовая", [0.4] * 30))
    j.add(запись("b-neg", "B", [0.35] * 30, note="трудные негативы"))
    таблица = j.table()
    assert "b-neg" in таблица
    assert ОТКЛОНЁН in таблица
    path = tmp_path / "journal.json"
    j.save(str(path))
    снова = Journal.load(str(path))
    assert [e.tag for e in снова.entries] == ["базовая", "b-neg"]
    assert снова.by_tag("b-neg").verdict == ОТКЛОНЁН


def test_журнала_нет_значит_пустой_журнал(tmp_path):
    assert Journal.load(str(tmp_path / "нет.json")).entries == []


def test_переделанный_лучший_этап_сравнивается_не_с_собой():
    """Этап можно переделать ключом --force, и при этом лучшим он остаётся
    сам. Сравнение с собой дало бы ноль и отняло у него вердикт, то есть
    он исчез бы из таблицы как принятый, а следующий этап сравнивался бы
    с базовой линией."""
    j = Journal()
    j.add(запись("базовая", "базовая", [0.40] * 40))
    rng = np.random.default_rng(3)
    j.add(запись("a-1ep", "A", [0.52 + float(rng.normal(0, 0.01)) for _ in range(40)]))
    assert j.best().tag == "a-1ep"
    снова = j.add(запись("a-1ep", "A", [0.54] * 40))
    assert снова.compared_with == "базовая"
    assert снова.verdict == ПРИНЯТ
    assert j.best().tag == "a-1ep"
