"""Отбраковка негодных вопросов.

Оба фильтра защищают метрики от вопросов, на которых измерение теряет смысл:
списанный с фрагмента сводит задачу к поиску подстроки, а слишком общий
не имеет правильного ответа вовсе.
"""
from __future__ import annotations

import pytest

from rufin.queryfilter import (
    IdfTable,
    copy_score,
    is_good_source,
    judge_query,
    longest_common_run,
)

ФРАГМЕНТЫ = [
    "Кредитная организация оценивает кредитный риск по каждой выданной ссуде.",
    "Резерв формируется при обесценении ссуды вследствие неисполнения обязательств.",
    "Оценка ссуды и формирование резерва производятся при возникновении оснований.",
    "Банк России устанавливает требования к порядку ведения кредитного досье.",
]


# Порог MIN_MEAN_IDF = 3.0 рассчитан на корпус в шестьдесят тысяч фрагментов.
# На четырёх документах максимальная обратная частота равна log(5) = 1,6,
# и порог не возьмёт ни один вопрос. Поэтому к содержательным фрагментам
# подмешивается фон: он делает редкое слово по-настоящему редким.
ФОН = [f"общие положения настоящего указания пункт {i}" for i in range(300)]


@pytest.fixture
def idf() -> IdfTable:
    return IdfTable(ФРАГМЕНТЫ + ФОН)


def test_общая_цепочка_измеряется_по_словам():
    assert longest_common_run(["а", "б", "в"], ["х", "а", "б", "у"]) == 2


def test_цепочки_нет_когда_слова_не_подряд():
    assert longest_common_run(["а", "б"], ["а", "х", "б"]) == 1


def test_пустой_вход_дает_ноль():
    assert longest_common_run([], ["а"]) == 0


def test_списанный_вопрос_виден_по_длине_цепочки():
    фрагмент = ФРАГМЕНТЫ[0]
    run, share = copy_score("Кредитная организация оценивает кредитный риск по ссуде?", фрагмент)
    assert run >= 5
    assert share > 0.5


def test_переформулированный_вопрос_цепочки_не_дает():
    run, _ = copy_score("Как часто банк пересматривает риск по выданным деньгам?", ФРАГМЕНТЫ[0])
    assert run <= 2


def test_общее_слово_весит_меньше_редкого(idf):
    # «ссуды» встречается в двух фрагментах, «досье» — в одном
    assert idf.idf("ссуды") < idf.idf("досье")


def test_списанный_вопрос_отклоняется(idf):
    ok, причина = judge_query(
        "Кредитная организация оценивает кредитный риск по каждой выданной ссуде?",
        ФРАГМЕНТЫ[0], idf)
    assert not ok and "списан" in причина


def test_слишком_общий_вопрос_отклоняется():
    # у такого вопроса нет правильного ответа, он только зашумляет метрики
    общий = IdfTable(["ссуда"] * 200)
    ok, причина = judge_query("Какие требования к ссуда ссуда ссуда?", "ссуда", общий)
    assert not ok and "многим" in причина


def test_не_вопрос_отклоняется(idf):
    ok, причина = judge_query("Порядок формирования резервов по ссудам.", ФРАГМЕНТЫ[0], idf)
    assert not ok and причина == "не вопрос"


def test_короткий_вопрос_отклоняется(idf):
    ok, причина = judge_query("Что это?", ФРАГМЕНТЫ[0], idf)
    assert not ok and причина == "слишком короткий"


def test_годный_вопрос_проходит(idf):
    ok, причина = judge_query(
        "Кто отвечает за периодичность вынесения профессионального суждения?",
        ФРАГМЕНТЫ[0], idf)
    assert ok, причина


def _фрагмент(тело: str, section: str = "Глава 1") -> dict:
    return {"text": f"Указание Банка России № 1-У\n\n{тело}", "section": section}


def test_содержательный_фрагмент_годится_в_источники():
    тело = ("Кредитная организация оценивает кредитный риск по ссуде на постоянной основе. "
            "Профессиональное суждение выносится по результатам комплексного анализа "
            "деятельности заемщика с учетом его финансового положения. "
            "Оценка ссуды осуществляется в течение срока, установленного документами. ") * 2
    assert is_good_source(_фрагмент(тело))


def test_короткий_фрагмент_не_годится():
    assert not is_good_source(_фрагмент("Слишком коротко."))


def test_приложение_не_годится():
    # приложения — это формы отчётности и таблицы, спросить о них нечего
    тело = "Содержательное правило про оценку риска. " * 30
    assert not is_good_source(_фрагмент(тело, section="Приложение 1"))


def test_таблица_цифр_не_годится():
    assert not is_good_source(_фрагмент("1 2 3 4 5 6 7 8 9 0 " * 60))


def test_перечень_ссылок_на_законы_не_годится():
    assert not is_good_source(_фрагмент("ст. 5 № 86-ФЗ, " * 60))
