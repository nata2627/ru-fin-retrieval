"""Отсечка негативов: негатив не должен оказаться неразмеченным позитивом.

Это самая дорогая ошибка обучения на негативах из выдачи. Кандидат берётся
из того, что поиск поставил высоко, а выдача не размечена: фрагмент
на втором месте вполне может отвечать на вопрос. Как негатив он прямо
учит модель отталкивать правильный ответ, и по лоссу этого не видно —
он падает как положено.

Проверяется каждое из трёх правил по отдельности и то, что шкала оценок
определяется, а не угадывается: порог 0,5 в логитах и в вероятностях —
это совершенно разные пороги.
"""
from __future__ import annotations

import math

import pytest

from rufin.training.negatives import (
    БЛИЗКО_К_ЭТАЛОНУ,
    ВЫШЕ_ПОРОГА,
    НЕ_ИЗ_ОБУЧАЮЩИХ,
    ТОТ_ЖЕ_АКТ,
    NegativeRules,
    detect_scale,
    logit,
    pick_all,
    pick_negatives,
    probability,
)


def лог(p: float) -> float:
    """Логит по вероятности: так в тестах читаются пороги, а не числа."""
    return math.log(p / (1 - p))


def запись(кандидаты, gold_p=0.95, gold="590-П_28062017#0001", qid="tr00001") -> dict:
    return {"query_id": qid, "gold_chunk_id": gold, "gold_score": лог(gold_p),
            "candidates": [[c, лог(p)] for c, p in кандидаты]}


ПРАВИЛА = NegativeRules(max_score=0.5, absolute_margin=0.10, drop_same_act=True,
                        per_query=2)


def test_кандидат_которого_учитель_считает_релевантным_не_негатив():
    """Порог 0,5 — собственная граница решения кросс-энкодера. Спорить
    с учителем, из которого мы же и дистиллируем, бессмысленно."""
    pick = pick_negatives(запись([("300-П_01012020#0005", 0.80),
                                  ("400-П_01012020#0007", 0.02)]), ПРАВИЛА)
    assert pick.negatives == ["400-П_01012020#0007"]
    assert pick.dropped[ВЫШЕ_ПОРОГА] == 1


def test_отступ_от_эталона_работает_и_ниже_абсолютного_порога():
    """Эталон с оценкой 0,30 — учитель в нём не уверен. Тогда кандидат
    на 0,28 неотличим от эталона для самого учителя, хотя до 0,5 ему далеко."""
    pick = pick_negatives(запись([("300-П_01012020#0005", 0.28),
                                  ("400-П_01012020#0007", 0.05)], gold_p=0.30), ПРАВИЛА)
    assert pick.negatives == ["400-П_01012020#0007"]
    assert pick.dropped[БЛИЗКО_К_ЭТАЛОНУ] == 1


def test_фрагменты_того_же_акта_выбрасываются():
    """Нарезка идёт с перекрытием 15%: соседний фрагмент акта буквально
    содержит часть текста эталона. Как негатив он почти всегда ложный,
    а выглядит идеальным трудным негативом."""
    pick = pick_negatives(запись([("590-П_28062017#0002", 0.10),
                                  ("400-П_01012020#0007", 0.10)]), ПРАВИЛА)
    assert pick.negatives == ["400-П_01012020#0007"]
    assert pick.dropped[ТОТ_ЖЕ_АКТ] == 1


def test_кандидаты_не_из_обучающих_актов_выбрасываются():
    """Негатив из акта dev не портит разметку, но даёт модели увидеть его
    текст на обучении, а весь смысл сплита по актам в том, что не видела."""
    правила = NegativeRules(per_query=2, train_acts=frozenset({"590-П_28062017",
                                                              "400-П_01012020"}))
    pick = pick_negatives(запись([("777-У_01012021#0001", 0.10),
                                  ("400-П_01012020#0007", 0.10)]), правила)
    assert pick.negatives == ["400-П_01012020#0007"]
    assert pick.dropped[НЕ_ИЗ_ОБУЧАЮЩИХ] == 1


def test_сам_эталон_не_попадает_в_негативы():
    pick = pick_negatives(запись([("590-П_28062017#0001", 0.95),
                                  ("400-П_01012020#0007", 0.10)]), ПРАВИЛА)
    assert pick.negatives == ["400-П_01012020#0007"]


def test_берётся_не_больше_нормы_и_в_порядке_выдачи():
    кандидаты = [(f"{n}00-П_01012020#0001", 0.2 - 0.01 * i)
                 for i, n in enumerate((3, 4, 5, 6))]
    pick = pick_negatives(запись(кандидаты), ПРАВИЛА)
    assert pick.negatives == ["300-П_01012020#0001", "400-П_01012020#0001"]


def test_вопрос_может_остаться_без_негативов_и_это_не_ошибка():
    """Такой вопрос просто не идёт в набор этапа B, а в контрастиве
    этапа A по-прежнему участвует."""
    pick = pick_negatives(запись([("300-П_01012020#0005", 0.90)]), ПРАВИЛА)
    assert pick.negatives == []


def test_статистика_считает_вопросы_без_негативов():
    записи = [запись([("300-П_01012020#0001", 0.02),
                      ("400-П_01012020#0001", 0.03)], qid="tr1"),
              запись([("300-П_01012020#0001", 0.90)], qid="tr2")]
    отбор, stats = pick_all(записи, ПРАВИЛА)
    assert stats["вопросов"] == 2
    assert stats["хватило негативов"] == 1
    assert stats["без негативов вовсе"] == 1
    assert отбор["tr2"] == []
    # пороги уезжают в отчёт вместе со статистикой
    assert stats["правила"]["max_score"] == 0.5


# ---- шкала оценок ----

def test_шкала_определяется_по_разбросу():
    assert detect_scale([0.0, 0.3, 0.99]) == "sigmoid"
    assert detect_scale([-8.1, 0.3, 11.0]) == "logit"


def test_вероятность_и_логит_обратны_друг_другу():
    for p in (0.001, 0.1, 0.5, 0.9, 0.999):
        assert probability(лог(p)) == pytest.approx(p, abs=1e-9)
        assert logit(p, "sigmoid") == pytest.approx(лог(p), abs=1e-9)


def test_сигмоида_не_переполняется_на_крайних_логитах():
    assert probability(-800.0) == pytest.approx(0.0)
    assert probability(800.0) == pytest.approx(1.0)


def test_оценки_в_шкале_сигмоиды_читаются_как_вероятности():
    """Если обёртка применила сигмоиду сама, пороги обязаны сработать
    так же. Иначе отсечка либо пропускает всё, либо режет всё."""
    rec = {"query_id": "tr1", "gold_chunk_id": "590-П_28062017#0001",
           "gold_score": 0.95,
           "candidates": [["300-П_01012020#0005", 0.80],
                          ["400-П_01012020#0007", 0.02]]}
    pick = pick_negatives(rec, ПРАВИЛА, scale="sigmoid")
    assert pick.negatives == ["400-П_01012020#0007"]


def test_неизвестная_шкала_это_отказ():
    with pytest.raises(ValueError, match="шкала"):
        probability(0.5, "вероятность")
