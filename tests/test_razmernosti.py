"""Размерности из результата оценки достаются без сравнения числа со строкой.

Падение в этом месте стоило шестнадцати минут видеокарты. Этап матрёшки
обучился, оценился по всем трём размерностям, и упала строка отчёта:
`sorted` по словарю, где ключи это и размерности числами, и «секунд
на корпус» строкой.

Беда не в самой строке, а в том, что словарь смешанный. Поэтому проверка
здесь не на одну строку, а на то, что доставалка размерностей переживает
такой словарь.
"""
from __future__ import annotations

import os
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "kaggle"))
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

import gpu_traineval as E  # noqa: E402


def test_смешанный_словарь_не_роняет():
    итог = {384: {"NDCG@10": 1}, 256: {"NDCG@10": 2}, 128: {"NDCG@10": 3},
            "секунд на корпус": 219.0}
    assert E.размерности(итог) == [384, 256, 128]


def test_одна_размерность():
    assert E.размерности({384: {}, "секунд на корпус": 1.0}) == [384]


def test_прямой_sorted_по_такому_словарю_падает():
    """Фиксируем саму ловушку: именно так и было написано, и именно так
    упало после шестнадцати минут обучения."""
    итог = {384: {}, 256: {}, "секунд на корпус": 1.0}
    with pytest.raises(TypeError):
        sorted(итог)


def test_первая_размерность_всегда_полная():
    """Полной считается наибольшая. По ней идёт строка журнала, а урезанные
    печатаются отдельно."""
    assert E.размерности({128: {}, 384: {}, 256: {}, "с": 0})[0] == 384
