"""Отчёт подготовки D0 собирается без падений, в том числе на краях.

Эта часть исполняется ровно один раз, в самом конце многочасового прогона.
Ошибка в ней обнуляет всю работу, а обнаруживается через несколько часов
после начала. Проверять её на видеокарте значит платить часами за каждую
опечатку, поэтому она вынесена в функцию и проверяется здесь.

Один такой случай уже был и ловится тестом ниже: число пройденных пар
бралось из переменной цикла, а при продолжении прогона, когда считать
нечего, цикл не делает ни витка.
"""
from __future__ import annotations

import json
import math
import os
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "kaggle"))

import gpu_prepare as G  # noqa: E402


class Ключи:
    """Разбор командной строки подменён: отчёту нужны три поля."""

    per_query = 2
    depth = 30
    dense = False
    teacher = "BAAI/bge-reranker-v2-m3"
    student = "intfloat/multilingual-e5-small"


def лог(p: float) -> float:
    return math.log(p / (1 - p))


def запись(qid: str, место: int = 1) -> dict:
    return {"query_id": qid, "gold_chunk_id": "590-П_28062017#0001",
            "gold_score": лог(0.95), "teacher_place": место,
            "candidates": [["590-П_28062017#0001", лог(0.95)],
                           ["400-П_01012020#0007", лог(0.04)],
                           ["300-П_01012020#0005", лог(0.02)]]}


АКТЫ = frozenset({"590-П_28062017", "400-П_01012020", "300-П_01012020"})


def test_отчёт_собирается_и_переживает_запись_в_json():
    записи = [запись(f"tr{i:05d}", место=(i % 5) + 1) for i in range(40)]
    отчёт = G.собрать_отчёт(записи, "logit", АКТЫ, Ключи(), {"глубина": 30})
    assert отчёт["вопросов"] == 40
    assert отчёт["медиана места эталона у учителя"] >= 1
    assert отчёт["эталон первым у учителя"] == 8
    # отчёт уезжает файлом, значит обязан сериализоваться целиком
    json.dumps(отчёт, ensure_ascii=False)


def test_продолженный_прогон_без_новой_работы_не_падает():
    """Законный исход: всё посчитано прошлым прогоном, считать нечего.
    Падать тут нельзя — работа уже сделана, теряется только отчёт."""
    отчёт = G.собрать_отчёт([], "logit", АКТЫ, Ключи(), {})
    assert отчёт["вопросов"] == 0
    assert отчёт["медиана места эталона у учителя"] == 0
    json.dumps(отчёт, ensure_ascii=False)


def test_в_отчёте_есть_статистика_негативов():
    """Без неё не видно, сработала ли отсечка, а это единственное место,
    где ложные негативы заметны до обучения."""
    отчёт = G.собрать_отчёт([запись("tr1")], "logit", АКТЫ, Ключи(), {})
    stats = отчёт["негативы"]
    assert "отброшено кандидатов" in stats
    assert stats["правила"]["per_query"] == 2


@pytest.mark.parametrize("scale", ["logit", "sigmoid"])
def test_обе_шкалы_проходят(scale):
    записи = [запись("tr1")] if scale == "logit" else [
        dict(запись("tr1"), gold_score=0.95,
             candidates=[["590-П_28062017#0001", 0.95], ["400-П_01012020#0007", 0.04]])]
    отчёт = G.собрать_отчёт(записи, scale, АКТЫ, Ключи(), {})
    assert отчёт["шкала оценок"] == scale
