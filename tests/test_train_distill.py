"""Список для дистилляции: длина, порядок и шкала оценок.

Три вещи ломаются здесь молча. Список переменной длины `datasets` просто
не соберёт в таблицу — это как раз шумная поломка. А вот оценки, оставленные
в вероятностях вместо логитов, softmax проглотит: распределение выйдет почти
ровным, ученик получит слабый сигнал, и выглядеть это будет как «дистилляция
не помогла». И фрагмент, которого нет в разрешённых текстах, молча сдвинул бы
список, если его не отбрасывать.
"""
from __future__ import annotations

import math

from rufin.training.pairs import build_pairs
from rufin.training.trainer import build_distill_columns

ТЕКСТЫ = {f"590-П_28062017#{i:04d}": f"текст фрагмента {i}" for i in range(1, 12)}
ТЕКСТЫ["447-П_22122014#0005"] = "другой акт"


def лог(p: float) -> float:
    return math.log(p / (1 - p))


def пары():
    вопросы = [{"query_id": "tr1", "text": "Как оценивается риск?",
                "gold_chunk_id": "590-П_28062017#0001"}]
    p, _ = build_pairs(вопросы, ТЕКСТЫ)
    return p


def подготовка(кандидаты, gold="590-П_28062017#0001", gold_p=0.95) -> dict:
    return {"tr1": {"query_id": "tr1", "gold_chunk_id": gold,
                    "gold_score": лог(gold_p),
                    "candidates": [[c, лог(p)] for c, p in кандидаты]}}


def test_эталон_первым_и_список_ровно_нужной_длины():
    кандидаты = [(f"590-П_28062017#{i:04d}", 0.5 - 0.01 * i) for i in range(2, 12)]
    cols = build_distill_columns(пары(), подготовка(кандидаты), ТЕКСТЫ, 4, "logit")
    assert len(cols["anchor"]) == 1
    assert sorted(cols) == ["anchor", "doc_1", "doc_2", "doc_3", "doc_4", "label"]
    assert cols["doc_1"][0] == "passage: текст фрагмента 1"
    assert len(cols["label"][0]) == 4
    # оценка эталона стоит первой и она самая высокая
    assert cols["label"][0][0] == max(cols["label"][0])


def test_вопрос_с_недобором_кандидатов_в_набор_не_идёт():
    """Молча добить список повтором значило бы отдать учителю два одинаковых
    документа и спросить, какой уместнее."""
    cols = build_distill_columns(пары(), подготовка([("590-П_28062017#0002", 0.3)]),
                                 ТЕКСТЫ, 4, "logit")
    assert cols["anchor"] == []
    assert cols["doc_4"] == []


def test_фрагменты_без_текста_пропускаются_а_не_сдвигают_список():
    кандидаты = [("999-П_01012000#0001", 0.4), ("590-П_28062017#0002", 0.3),
                 ("590-П_28062017#0003", 0.2)]
    cols = build_distill_columns(пары(), подготовка(кандидаты), ТЕКСТЫ, 3, "logit")
    assert cols["doc_2"][0] == "passage: текст фрагмента 2"
    assert cols["doc_3"][0] == "passage: текст фрагмента 3"


def test_оценки_приводятся_к_логитам_если_приехали_вероятностями():
    """В вероятностях разброс оценок лежит в единице, и softmax по нему
    почти ровный: ученик получал бы слабый сигнал независимо от того,
    насколько он ошибся."""
    подг = {"tr1": {"query_id": "tr1", "gold_chunk_id": "590-П_28062017#0001",
                    "gold_score": 0.95,
                    "candidates": [["590-П_28062017#0002", 0.2],
                                   ["590-П_28062017#0003", 0.1]]}}
    cols = build_distill_columns(пары(), подг, ТЕКСТЫ, 3, "sigmoid")
    метки = cols["label"][0]
    assert метки[0] == max(метки)
    # разброс в логитах заметно больше единицы, иначе приведения не было
    assert max(метки) - min(метки) > 1.0


def test_вопроса_нет_в_подготовке_значит_строки_нет():
    cols = build_distill_columns(пары(), {}, ТЕКСТЫ, 3, "logit")
    assert cols["anchor"] == []
