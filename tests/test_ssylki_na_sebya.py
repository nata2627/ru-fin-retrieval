"""Вопрос не должен ссылаться на фрагмент, по которому написан.

«Какую сумму формулирует этот фрагмент» — бессмысленный поисковый запрос:
фрагмента у пользователя перед глазами нет, искать нечего. Модель пишет
такое, когда сбивается с задачи «составь вопрос» на «перескажи текст».
Прежние фильтры этого не ловят: вопрос не списан и вполне конкретен.
Обе формулировки взяты с пробы 30.09.2026.
"""
from __future__ import annotations

import pytest

from rufin.queryfilter import IdfTable, judge_query, ssylaetsya_na_sebya


@pytest.mark.parametrize("вопрос", [
    "Какую сумму формулирует этот фрагмент по отношению к риску?",
    "Каковы условия, определяющие размер надбавки, согласно данному положению?",
    "Что сказано в приведённом пункте о сроках представления?",
    "Какие требования установлены в настоящем документе?",
    "Что следует из данного текста о порядке расчёта?",
])
def test_самоссылки_отсеиваются(вопрос):
    assert ssylaetsya_na_sebya(вопрос)


@pytest.mark.parametrize("вопрос", [
    "Какой коэффициент риска применяется для секьюритизационных сделок?",
    "резерв по ссуде третьей категории качества",
    "Какие сведения указываются в заявке на приобретение инвестиционных паев?",
    # «данные» и «этот отчёт» — не отсылки к фрагменту, а предмет вопроса
    "Что относится к данным бухгалтерского учёта кредитной организации?",
    "Какой срок установлен для представления этого отчёта в Банк России?",
])
def test_законные_вопросы_проходят(вопрос):
    assert not ssylaetsya_na_sebya(вопрос)


def test_фильтр_встроен_в_общую_проверку():
    idf = IdfTable(["резерв по ссуде", "кредитный риск", "надбавка к капиталу"])
    ладно, почему = judge_query(
        "Каковы условия, определяющие размер надбавки, согласно данному положению?",
        "Размер национальной антициклической надбавки определяется величиной "
        "кредитного гэпа и устанавливается решением Совета директоров.", idf)
    assert not ладно
    assert почему == "ссылается на сам фрагмент"
