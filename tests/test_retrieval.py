"""Токенизация, BM25 и слияние выдач.

BM25 здесь свой, а не rank_bm25 — ради памяти. Раз формула переписана,
её надо сверять с общепринятой, иначе базовая линия окажется своя
собственная и сравнивать проект будет не с чем.
"""
from __future__ import annotations

import numpy as np
import pytest

from rufin.retrieval.bm25 import BM25Index
from rufin.retrieval.hybrid import RRF_K, rrf
from rufin.retrieval.text import normalize_query, tokenize

КОРПУС = [
    ("c1", "Кредитная организация формирует резерв на возможные потери по ссудам."),
    ("c2", "Резерв по портфелю однородных ссуд формируется в размере, "
           "установленном внутренними документами."),
    ("c3", "Отзыв лицензии на осуществление банковских операций оформляется приказом."),
    ("c4", "Резерв корректируется при изменении категории качества ссуды."),
]


# ---------- токенизация ----------

def test_номер_акта_остается_одним_токеном():
    # по номеру часто и ищут; разбиение на «590» и «п» такой запрос убивает
    assert "590-п" in tokenize("Положение 590-П о резервах")


def test_служебные_слова_выбрасываются():
    assert tokenize("и в о при") == []


def test_регистр_не_важен():
    assert tokenize("РЕЗЕРВ") == tokenize("резерв") == ["резерв"]


def test_канцелярский_зачин_снимается():
    assert normalize_query("Каков порядок формирования резервов?").startswith("порядок")


def test_сокращение_раскрывается():
    assert "кредитная организация" in normalize_query("Какие требования к КО?")


def test_запрос_из_одного_зачина_не_исчезает():
    # снять всё и вернуть пустую строку хуже, чем не трогать
    assert normalize_query("Каков") == "Каков"


# ---------- BM25 ----------

@pytest.fixture
def индекс() -> BM25Index:
    ids, texts = zip(*КОРПУС)
    return BM25Index.build(list(ids), list(texts))


def test_находит_документ_по_редкому_слову(индекс):
    assert индекс.search("отзыв лицензии", k=1)[0][0] == "c3"


def test_редкое_слово_весит_больше_частого(индекс):
    # «резерв» есть в трёх документах из четырёх, «портфель» — в одном
    assert индекс.idf[индекс.vocab["портфелю"]] > индекс.idf[индекс.vocab["резерв"]]


def test_отрицательный_вес_заменяется(индекс):
    # у Okapi слово из большинства документов получает отрицательный вес
    # и начинает работать против документов, где оно есть
    assert индекс.idf.min() > 0


def test_неизвестное_слово_не_ломает_поиск(индекс):
    assert индекс.search("криптовалюта", k=3) != []


def test_срез_больше_корпуса_отдает_весь_корпус(индекс):
    assert len(индекс.search("резерв", k=100)) == len(КОРПУС)


def test_выдача_упорядочена_по_убыванию(индекс):
    scores = [s for _, s in индекс.search("резерв по ссудам", k=4)]
    assert scores == sorted(scores, reverse=True)


def test_буфер_оценок_переиспользуется_без_следов(индекс):
    # оценки живут в общем буфере между запросами: не обнули его —
    # и второй запрос получит хвост первого
    первый = индекс.scores("отзыв лицензии").copy()
    индекс.scores("резерв портфель ссуда")
    assert np.allclose(индекс.scores("отзыв лицензии"), первый)


def test_индекс_знает_свой_размер(индекс):
    assert индекс.size_mb > 0


def test_формула_совпадает_с_rank_bm25(индекс):
    """Сверка с общепринятой реализацией на тех же токенах.

    Прогоном `make check-bm25` то же самое проверяется на всём корпусе
    и расходится на 1,4e-06. Здесь — быстрый вариант для CI.
    """
    rank_bm25 = pytest.importorskip("rank_bm25")
    свои = [tokenize(t) for _, t in КОРПУС]
    чужой = rank_bm25.BM25Okapi(свои)
    запрос = "резерв по ссудам"
    assert np.allclose(чужой.get_scores(tokenize(запрос)), индекс.scores(запрос), atol=1e-5)


# ---------- слияние выдач ----------

def test_rrf_поднимает_стабильного_середняка():
    # b не первый ни в одной выдаче, но вторым не бывает — и обходит обоих
    слито = rrf([[("a", 9.0), ("b", 8.0), ("c", 7.0)],
                 [("b", 5.0), ("c", 4.0), ("a", 1.0)]])
    assert [d for d, _ in слито] == ["b", "a", "c"]


def test_rrf_складывает_обратные_ранги_а_не_оценки():
    # оценки BM25 и косинуса живут в разных шкалах и несопоставимы;
    # огромная оценка в одной выдаче не должна перевешивать вторую
    слито = dict(rrf([[("a", 1000.0)], [("b", 0.01), ("a", 0.001)]]))
    assert слито["a"] == pytest.approx(1 / (RRF_K + 1) + 1 / (RRF_K + 2))


def test_rrf_не_теряет_документ_из_одной_выдачи():
    слито = dict(rrf([[("a", 1.0)], [("b", 1.0)]]))
    assert set(слито) == {"a", "b"}


def test_rrf_обрезает_по_глубине():
    выдача = [(f"d{i}", 1.0) for i in range(50)]
    assert len(rrf([выдача], top=10)) == 10
