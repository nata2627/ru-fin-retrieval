"""Вопрос обязан быть русским: модель для теста уходит в другие языки.

Модель-генератор теста берётся из другого семейства нарочно — иначе тест
померил бы, насколько ученик выучил стиль своего же генератора. Но другое
семейство хуже держит русский: Mistral-7B-Instruct на пробе 30.09.2026
выдал одиннадцать английских вопросов из двадцати в тесте, шесть из двадцати
в dev и один украинский. Остальные фильтры этого не ловят — английский
вопрос не списан с фрагмента и вполне конкретен.
"""
from __future__ import annotations

import pytest

from rufin.queryfilter import po_russki


@pytest.mark.parametrize("вопрос", [
    "Какой коэффициент риска применяется для секьюритизационных сделок?",
    "резерв по ссуде третьей категории качества",
    "Как отражаются обязательства по валюте USD в отчётных периодах?",
    "Что относится к отчётности по МСФО (IFRS) 9?",
    "Нужно ли направлять сообщение через SWIFT при таком переводе?",
])
def test_русские_вопросы_проходят(вопрос):
    ладно, почему = po_russki(вопрос)
    assert ладно, почему


@pytest.mark.parametrize("вопрос", [
    "What information must a foreign bank branch report to the Bank of Russia?",
    "What is the consequence for a bank if the agency fails to notify in time?",
])
def test_английские_отбрасываются(вопрос):
    ладно, почему = po_russki(вопрос)
    assert not ладно
    assert почему == "не по-русски"


def test_соседний_язык_отбрасывается():
    """Одна буква, которой в русском нет, — признак, что модель сползла."""
    ладно, почему = po_russki("Какие методы оценки справедливой стоимости "
                              "финансовых активів утверждает организация?")
    assert not ладно
    assert "соседний язык" in почему


def test_строка_без_букв_отбрасывается():
    ладно, почему = po_russki("12345 (6.7) — 8,9%")
    assert not ладно
    assert почему == "без букв"


def test_фильтр_встроен_в_общую_проверку():
    """Английский вопрос не должен доходить до остальных проверок:
    он не списан с фрагмента и вполне конкретен, они его пропустят."""
    from rufin.queryfilter import IdfTable, judge_query
    idf = IdfTable(["резерв по ссуде", "кредитный риск банка", "отчётность"])
    ладно, почему = judge_query(
        "What information must a foreign bank branch report to the regulator?",
        "Филиал иностранного банка представляет в Банк России сведения "
        "об источниках средств.", idf)
    assert not ладно
    assert почему == "не по-русски"
