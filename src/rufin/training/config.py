"""Рецепт обучения: один этап — один объект, все числа в одном месте.

**Каждый этап обучается с исходных весов `multilingual-e5-small`,
а не поверх весов предыдущего.** Рецепт наращивается составом, а не
дообучением по кругу, и причин тому три.

Первая: этап A перебирает длительность обучения (одна, две, три эпохи),
а этап E — число эпох поверх лучшего состава. Если начинать с уже
обученных весов, эпохи складываются, и «две эпохи» перестаёт означать
две эпохи.

Вторая: отклонённый этап не должен оставлять следа. При дообучении
по цепочке он его оставляет — веса уже сдвинуты, и отказаться от шага
можно только откатившись, то есть всё равно обучившись заново.

Третья: так таблица читается как ответ на вопрос «что даёт эта
составляющая рецепта», а не «что даёт ещё один проход по данным».

Состав наращивается: B это A плюс трудные негативы, C это B плюс
дистилляция, D это C плюс матрёшка. Поле `extends` хранит эту
родословную для отчёта.

Про типы данных. На T4 нет bf16 — это Turing. Обучение идёт в fp32:
для модели на 118M памяти хватает с запасом, а выигрыш fp16 по времени
здесь не нужен и стоит риска молчаливого расхождения. Поэтому поля
«половинная точность» в конфигурации нет вовсе: её нельзя включить
случайно.

Про размер батча на этапе C. Контрастив считается батчем 128 при мини-батче
32 — это GradCache: он держит в памяти только эмбеддинги, а не активации
всех 128 текстов. У списочной дистилляции такого приёма нет: на каждый
вопрос приходится `distill_docs` документов, и батч 128 означал бы тысячу
проходов энкодера за шаг. Зато у неё нет и связи между примерами в батче —
потери считаются по каждому вопросу отдельно, поэтому накопление градиента
математически равно большому батчу. Отсюда батч 16 и накопление 8 шагов:
эффективный размер тот же 128, памяти нужно в восемь раз меньше.
"""
from __future__ import annotations

from dataclasses import dataclass, replace

# Ученик. Путь, а не имя из `model_specs`: там имя означает «запись
# в таблице моделей», а здесь — веса, с которых начинается обучение.
STUDENT = "intfloat/multilingual-e5-small"
# Учитель — тот же кросс-энкодер, которым измерен потолок без обучения
# (0,690 против 0,483 у BM25). Разрыв в 0,207 и есть то, что переносится.
TEACHER = "BAAI/bge-reranker-v2-m3"

# Префиксы берутся из `model_specs`, а не пишутся здесь руками: обучение
# и оценка обязаны пользоваться одними и теми же. Расхождение испортит
# качество, а причина будет неочевидна.
SPEC = "e5-small"


@dataclass(frozen=True)
class TrainConfig:
    """Один этап рецепта."""

    tag: str                       # имя папки с весами и строки в таблице
    stage: str                     # A, A+, B, C, D, E — для группировки в отчёте
    note: str = ""
    extends: str = ""              # чей состав расширяет; только для отчёта
    datasets: tuple[str, ...] = ("pairs",)
    # «pairs» — контрастив; «distill» — списочная KL из кросс-энкодера.
    # Оба вместе: у них разные столбцы, и обучение идёт двумя наборами
    # с двумя функциями потерь.
    with_negatives: bool = False   # добавлять ли трудные негативы в пары
    epochs: float = 1.0
    batch: int = 128
    mini_batch: int = 32           # GradCache: сколько текстов за один проход
    accumulate: int = 1
    lr: float = 2e-5
    warmup_ratio: float = 0.1
    weight_decay: float = 0.01
    scale: float = 20.0            # множитель косинуса перед softmax, как в MNRL
    kl_temperature: float = 1.0
    distill_docs: int = 8          # сколько документов в списке на один вопрос
    negatives_per_query: int = 2
    matryoshka: tuple[int, ...] = ()
    max_seq_length: int = 512
    freeze_vocabulary: bool = True
    seed: int = 13

    @property
    def effective_batch(self) -> int:
        return self.batch * self.accumulate

    def as_dict(self) -> dict:
        return dict(self.__dict__)


# ---- этап A: контрастив на синтетике, три длительности ----
# Основной прирост ожидается здесь. Батч 128 при мини-батче 32 — это
# CachedMultipleNegativesRankingLoss с GradCache: негативами служат
# эталоны остальных вопросов батча, и чем батч больше, тем задача труднее.
A = TrainConfig(
    tag="a-1ep", stage="A", epochs=1.0,
    note="контрастив, батч 128 при мини-батче 32, словарь заморожен")

STAGE_A = (
    A,
    replace(A, tag="a-2ep", stage="A+", extends="a-1ep", epochs=2.0,
            note="то же, две эпохи"),
    replace(A, tag="a-3ep", stage="A+", extends="a-1ep", epochs=3.0,
            note="то же, три эпохи"),
)

# ---- этап B: трудные негативы ----
# Негативы берутся из гибридной выдачи по обучающим актам и просеиваются
# по оценке учителя (см. `negatives`). Ожидание скромное: +0,01–0,02.
B = TrainConfig(
    tag="b-neg", stage="B", extends="a-1ep", with_negatives=True, epochs=1.0,
    note="трудные негативы из гибридной выдачи, отсечка по оценке позитива")
STAGE_B = (B,)

# ---- этап C: дистилляция ранжирования ----
# Главная ставка. Учитель ставит оценку каждому документу списка, ученик
# повторяет не ответ, а распределение по списку — отсюда KL, а не MSE.
# Контрастив оставлен вторым набором: без него ученик учится только
# различать близкие документы и теряет глобальную шкалу.
C = TrainConfig(
    tag="c-kl", stage="C", extends="b-neg",
    datasets=("pairs", "distill"), with_negatives=True,
    epochs=1.0, batch=16, accumulate=8, mini_batch=16,
    note="KL по списку из 8 документов плюс контрастив")
STAGE_C = (C,)

# ---- этап D: матрёшка ----
# Качество здесь расти не обязано. Задача другая: получить вектор, который
# можно обрезать до 256 и 128 без переобучения, то есть уменьшить индекс
# втрое. Поэтому этап принимается по применимости, если dev не просел.
D = replace(C, tag="d-matryoshka", stage="D", extends="c-kl",
            matryoshka=(384, 256, 128),
            note="матрёшка 384 / 256 / 128 поверх состава этапа C")
STAGE_D = (D,)

# ---- этап E: число эпох и температура ----
# Сетка маленькая нарочно: dev на 300 вопросах даёт интервал ±0,045,
# и перебор двух десятков точек по нему означал бы выбор шума.
EPOCHS_GRID = (2.0, 3.0)
TEMPERATURE_GRID = (0.5, 2.0)


def stage_e(base: TrainConfig) -> tuple[TrainConfig, ...]:
    """Сетка этапа E поверх состава лучшего принятого этапа.

    «Поверх лучшего» означает поверх его **состава**, а не его весов:
    обучение всё равно начинается с исходных, иначе число эпох перестаёт
    быть числом эпох (см. начало модуля).
    """
    out = []
    for epochs in EPOCHS_GRID:
        for temperature in TEMPERATURE_GRID:
            метка = f"e-{epochs:g}ep-t{temperature:g}".replace(".", "")
            out.append(replace(
                base, tag=метка, stage="E", extends=base.tag,
                epochs=epochs, kl_temperature=temperature,
                note=f"{epochs:g} эпохи, температура KL {temperature:g}, "
                     f"состав {base.tag}"))
    return tuple(out)


STAGE_E = stage_e(C)

RECIPE: tuple[TrainConfig, ...] = STAGE_A + STAGE_B + STAGE_C + STAGE_D + STAGE_E
BY_TAG: dict[str, TrainConfig] = {c.tag: c for c in RECIPE}

# Порядок этапов в отчёте и в прогоне.
ORDER = ("A", "A+", "B", "C", "D", "E")

if len(BY_TAG) != len(RECIPE):  # pragma: no cover — ловится при импорте
    raise RuntimeError("метки этапов рецепта повторяются: папка весов "
                       "и строка таблицы назначаются по метке")
