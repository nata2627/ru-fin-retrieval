"""Рецепт обучения: один этап — один объект, все числа в одном месте.

**Каждый этап обучается с исходных весов `multilingual-e5-small`,
а не поверх весов предыдущего.** Рецепт наращивается составом, а не
дообучением по кругу, и причин тому три.

Первая: этап A перебирает длительность обучения (одна, две, три эпохи),
а этап E — число эпох поверх лучшего состава. Если начинать с уже
обученных весов, эпохи складываются, и «две эпохи» перестаёт означать
две эпохи.

Вторая: отклонённый этап не должен оставлять следа. При дообучении
по цепочке он его оставляет — веса уже сдвинуты, и отказаться от шага
можно только откатившись, то есть всё равно обучившись заново.

Третья: так таблица читается как ответ на вопрос «что даёт эта
составляющая рецепта», а не «что даёт ещё один проход по данным».

Состав наращивается: B это A плюс трудные негативы, C это B плюс
дистилляция, D это C плюс матрёшка. Поле `extends` хранит эту
родословную для отчёта.

Про типы данных. На T4 нет bf16 — это Turing. Обучение идёт в fp32:
для модели на 118M памяти хватает с запасом, а выигрыш fp16 по времени
здесь не нужен и стоит риска молчаливого расхождения. Поэтому поля
«половинная точность» в конфигурации нет вовсе: её нельзя включить
случайно.

Про размер батча и почему дистилляция идёт без контрастива.

Контрастив считается батчем 128 при мини-батче 32 — это GradCache: он
держит в памяти только эмбеддинги, а не активации всех 128 текстов.
У списочной дистилляции такого приёма нет: на каждый вопрос приходится
`distill_docs` документов, и батч 128 означал бы тысячу проходов энкодера
за шаг. Зато у неё нет и связи между примерами в батче — потери считаются
по каждому вопросу отдельно, поэтому накопление градиента математически
равно большому батчу. Отсюда батч 16 и накопление 8 шагов: эффективный
размер тот же 128, памяти нужно в восемь раз меньше.

**А вот контрастиву накопление не равносильно, и отсюда устройство этапа C.**
Негативами в нём служат эталоны остальных вопросов батча, поэтому батч 16
при накоплении 8 это не 128 негативов, а 16: задача становится легче,
а не дешевле. Библиотека же задаёт размер батча один на все наборы данных
обучения. Значит, учить контрастив и дистилляцию одновременно можно только
батчем 16, то есть ослабив контрастив втрое с лишним, — и тогда прирост
этапа C нельзя было бы отнести к дистилляции: он мерил бы сумму «добавили
дистилляцию, ослабили контрастив».

Поэтому этап C — **дистилляция вместо контрастива**, а их сочетание
вынесено отдельной строкой `c-oba` с честной пометкой, что контрастив
в ней идёт батчем 16. Две строки в таблице стоят лишнего прогона на
полчаса, а слитая строка стоила бы невозможности что-либо из неё прочесть.
"""
from __future__ import annotations

from dataclasses import dataclass, replace

# Ученик. Путь, а не имя из `model_specs`: там имя означает «запись
# в таблице моделей», а здесь — веса, с которых начинается обучение.
STUDENT = "intfloat/multilingual-e5-small"
# Учитель — тот же кросс-энкодер, которым измерен потолок без обучения
# (0,690 против 0,483 у BM25). Разрыв в 0,207 и есть то, что переносится.
TEACHER = "BAAI/bge-reranker-v2-m3"

# Префиксы берутся из `model_specs`, а не пишутся здесь руками: обучение
# и оценка обязаны пользоваться одними и теми же. Расхождение испортит
# качество, а причина будет неочевидна.
SPEC = "e5-small"


ПОЛЯ_КОРТЕЖИ = ("datasets", "matryoshka")


@dataclass(frozen=True)
class TrainConfig:
    """Один этап рецепта."""

    tag: str                       # имя папки с весами и строки в таблице
    stage: str                     # A, A+, B, C, D, E — для группировки в отчёте
    note: str = ""
    extends: str = ""              # чей состав расширяет; только для отчёта
    datasets: tuple[str, ...] = ("pairs",)
    # «pairs» — контрастив; «distill» — списочная KL из кросс-энкодера.
    # Оба вместе: у них разные столбцы, и обучение идёт двумя наборами
    # с двумя функциями потерь.
    with_negatives: bool = False   # добавлять ли трудные негативы в пары
    epochs: float = 1.0
    batch: int = 128
    mini_batch: int = 32           # GradCache: сколько текстов за один проход
    accumulate: int = 1
    lr: float = 2e-5
    warmup_ratio: float = 0.1
    weight_decay: float = 0.01
    scale: float = 20.0            # множитель косинуса перед softmax, как в MNRL
    kl_temperature: float = 1.0
    distill_docs: int = 8          # сколько документов в списке на один вопрос
    negatives_per_query: int = 2
    matryoshka: tuple[int, ...] = ()
    max_seq_length: int = 512
    freeze_vocabulary: bool = True
    seed: int = 13

    @property
    def effective_batch(self) -> int:
        return self.batch * self.accumulate

    def as_dict(self) -> dict:
        return dict(self.__dict__)

    @classmethod
    def from_dict(cls, raw: dict) -> "TrainConfig":
        """Собрать конфигурацию обратно из журнала.

        JSON не знает кортежей, и после записи-чтения `datasets`
        и `matryoshka` становятся списками. Приводить их обратно
        обязательно: по ним сравниваются составы этапов, а список
        и кортеж не равны друг другу.
        """
        поля = set(cls.__dataclass_fields__)
        взято = {k: v for k, v in raw.items() if k in поля}
        for имя in ПОЛЯ_КОРТЕЖИ:
            if имя in взято and взято[имя] is not None:
                взято[имя] = tuple(взято[имя])
        return cls(**взято)


# ---- этап A: контрастив на синтетике, три длительности ----
# Основной прирост ожидается здесь. Батч 128 при мини-батче 32 — это
# CachedMultipleNegativesRankingLoss с GradCache: негативами служат
# эталоны остальных вопросов батча, и чем батч больше, тем задача труднее.
A = TrainConfig(
    tag="a-1ep", stage="A", epochs=1.0,
    note="контрастив, батч 128 при мини-батче 32, словарь заморожен")

STAGE_A = (
    A,
    replace(A, tag="a-2ep", stage="A+", extends="a-1ep", epochs=2.0,
            note="то же, две эпохи"),
    replace(A, tag="a-3ep", stage="A+", extends="a-1ep", epochs=3.0,
            note="то же, три эпохи"),
)

# ---- этап B: трудные негативы ----
# Негативы берутся из гибридной выдачи по обучающим актам и просеиваются
# по оценке учителя (см. `negatives`). Ожидание скромное: +0,01–0,02.
B = TrainConfig(
    tag="b-neg", stage="B", extends="a-1ep", with_negatives=True, epochs=1.0,
    note="трудные негативы из гибридной выдачи, отсечка по оценке позитива")
STAGE_B = (B,)

# ---- этап C: дистилляция ранжирования ----
# Главная ставка. Учитель ставит оценку каждому документу списка, ученик
# повторяет не ответ, а распределение по списку — отсюда KL, а не MSE.
# Контрастива здесь нет нарочно: причина в начале модуля, и она в том,
# что иначе прирост этапа нельзя было бы отнести к дистилляции.
C = TrainConfig(
    tag="c-kl", stage="C", extends="b-neg",
    datasets=("distill",), with_negatives=True,
    epochs=1.0, batch=16, accumulate=8, mini_batch=16,
    note="KL по списку из 8 документов вместо контрастива")
# Сочетание — отдельной строкой, с пометкой про батч 16. Если она обгонит
# и C, и B, значит контрастив нужен даже ослабленным, и это тоже результат.
C_ОБА = replace(C, tag="c-oba", stage="C", extends="c-kl",
                datasets=("pairs", "distill"),
                note="дистилляция плюс контрастив; контрастив здесь идёт "
                     "батчем 16, а не 128 — библиотека задаёт размер батча "
                     "один на оба набора")
STAGE_C = (C, C_ОБА)


# ---- этап D: матрёшка ----
# Качество здесь расти не обязано. Задача другая: получить вектор, который
# можно обрезать до 256 и 128 без переобучения, то есть уменьшить индекс
# втрое. Поэтому этап принимается по применимости, если dev не просел.
def stage_d(base: TrainConfig) -> tuple[TrainConfig, ...]:
    """Матрёшка поверх состава лучшего принятого этапа."""
    return (replace(base, tag="d-matryoshka", stage="D", extends=base.tag,
                    matryoshka=(384, 256, 128),
                    note=f"матрёшка 384 / 256 / 128 поверх состава {base.tag}"),)


STAGE_D = stage_d(C)
D = STAGE_D[0]

# ---- этап E: число эпох и температура ----
# Сетка маленькая нарочно: dev на 300 вопросах даёт интервал ±0,045,
# и перебор двух десятков точек по нему означал бы выбор шума.
TEMPERATURE_GRID = (0.5, 2.0)
# Сколько ещё эпох пробовать сверх того, что оказалось лучшим. Не список
# абсолютных значений: лучшим может оказаться любое число эпох, и сетка
# из двух и трёх при лучшем в три эпохи половиной точек повторила бы
# уже посчитанное.
ЭПОХ_СВЕРХ = (1.0, 2.0)


def stage_e(base: TrainConfig) -> tuple[TrainConfig, ...]:
    """Сетка этапа E поверх состава лучшего принятого этапа.

    «Поверх лучшего» означает поверх его **состава**, а не его весов:
    обучение всё равно начинается с исходных, иначе число эпох перестаёт
    быть числом эпох (см. начало модуля).

    **Температура перебирается только там, где есть дистилляция.** Она
    входит в её функцию потерь и больше никуда; без дистилляции две точки
    сетки, отличающиеся только температурой, — это два побайтно одинаковых
    прогона. На этом рецепте такая сетка сожгла бы половину отведённых
    часов и положила бы в таблицу строку-двойник.

    **Число эпох отсчитывается от лучшего, а не задаётся списком.** Если
    лучшим оказались три эпохи, пробовать две и три бессмысленно: одна
    точка хуже заведомо, вторая уже посчитана. Пробуются следующие,
    четыре и пять, и это и есть вопрос, на который этап отвечает —
    продолжает ли расти качество с длительностью обучения.
    """
    out = []
    эпохи = tuple(base.epochs + сверх for сверх in ЭПОХ_СВЕРХ)
    температуры = TEMPERATURE_GRID if "distill" in base.datasets else (None,)
    for epochs in эпохи:
        for temperature in температуры:
            if temperature is None:
                метка = f"e-{epochs:g}ep"
                пояснение = (f"{epochs:g} эпохи поверх состава {base.tag}; "
                             f"температура не перебирается, дистилляции нет")
                out.append(replace(base, tag=метка, stage="E", extends=base.tag,
                                   epochs=epochs, note=пояснение))
                continue
            метка = f"e-{epochs:g}ep-t{temperature:g}".replace(".", "")
            out.append(replace(
                base, tag=метка, stage="E", extends=base.tag,
                epochs=epochs, kl_temperature=temperature,
                note=f"{epochs:g} эпохи, температура KL {temperature:g}, "
                     f"состав {base.tag}"))
    return tuple(out)


STAGE_E = stage_e(C)

# Этапы с заранее определённым составом: их конфигурация не зависит
# от того, что окажется лучшим.
FIXED: tuple[TrainConfig, ...] = STAGE_A + STAGE_B + STAGE_C
# Этапы D и E строятся от состава лучшего принятого, поэтому в рецепте
# они перечислены в варианте по умолчанию — для таблицы, тестов и ключа
# --tags. Во время прогона состав им назначает журнал.
RECIPE: tuple[TrainConfig, ...] = FIXED + STAGE_D + STAGE_E
BY_TAG: dict[str, TrainConfig] = {c.tag: c for c in RECIPE}

# Порядок этапов в отчёте и в прогоне.
ORDER = ("A", "A+", "B", "C", "D", "E")

if len(BY_TAG) != len(RECIPE):  # pragma: no cover — ловится при импорте
    raise RuntimeError("метки этапов рецепта повторяются: папка весов "
                       "и строка таблицы назначаются по метке")
