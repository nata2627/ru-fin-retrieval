"""Разметка пула: единая инструкция, согласие разметчиков, стратифицированная выборка.

Пул размечает языковая модель-судья — руками 600 запросов по 14 кандидатов
не размечает никто. Это нормальная практика, но у неё есть цена, и цену
надо назвать числом: судья — это прибор, а у прибора есть погрешность.
Мерится она так: человек размечает выборку в 150 пар, и по ней считается
каппа Коэна.

Чтобы каппа мерила согласие, а не разницу в инструкциях, инструкция должна
быть одна. Поэтому она лежит здесь текстом, отсюда попадает в подсказку
судье и в шапку листа для человека, а `docs/ANNOTATION_GUIDE.md` обязан
совпадать с ней дословно — это проверяется тестом.

Выборка для человека берётся стратифицированной по оценкам судьи. Случайная
выборка из пула состояла бы почти из одних нулей: пул на четырнадцать
кандидатов содержит один-два релевантных, и каппа на такой выборке
померила бы согласие в том, что случайный фрагмент нерелевантен.
"""
from __future__ import annotations

import random
from collections import Counter
from typing import Sequence

RUBRIC = """\
Оценивается пара «запрос — фрагмент нормативного акта». Нужна одна цифра.

2 — фрагмент прямо отвечает на запрос. Прочитав только его, можно дать
    ответ по существу, ничего не додумывая и не открывая другой документ.

1 — фрагмент относится к делу, но ответа не содержит: соседний пункт,
    определение употреблённого термина, отсылка к нужному правилу,
    общее правило там, где спрашивают про исключение.

0 — не относится: другая тема, другой вид операций, совпали только слова.

Правила, без которых оценки разойдутся:

— оценивается фрагмент, а не акт: «нужный акт, но не тот пункт» — это 0
  или 1, но не 2;
— если ответ в фрагменте есть, но частично, и вторая половина в соседнем
  пункте, ставится 1, а не 2;
— 2 ставится, только если фрагмент отвечает ТОМУ, КТО СПРАШИВАЕТ. Правило
  для некредитной финансовой организации — не прямой ответ на вопрос
  кредитной организации, даже если формулировка совпадает слово в слово.
  Это 1. То же про другой вид лица: правило для юридических лиц не отвечает
  на вопрос про индивидуальных предпринимателей;
— если в запросе несколько вопросов, 2 ставится, когда фрагмент полностью
  отвечает на главный из них; ответ на попутный вопрос при молчании
  о главном — это 1;
— между 0 и 1 граница такая: 1 ставится, если фрагмент продвигает
  к ответу — называет тот самый пункт, термин, счёт или механизм, о котором
  спрашивают. Совпадение темы в широком смысле («тоже про резервы», «тоже
  про отчётность», «тоже про залог») — это 0, а не 1;
— фрагменты нарезаны механически, и канцелярит с обрывом на полуслове сами
  по себе оценку не снижают. Но оценивается то, что в фрагменте ЕСТЬ:
  если текст обрывается там, где должен был начаться ответ, ответа в нём
  нет, и это 1, а не 2;
— если запрос непонятен без контекста, который в нём не назван, ставится 0:
  найти на него ответ нельзя и поиску это не в упрёк;
— незнание предмета — не повод ставить 1 «на всякий случай». Сомнение
  разрешается в пользу меньшей оценки.
"""


def cohen_kappa(a: Sequence[int], b: Sequence[int], weighted: bool = False) -> float:
    """Каппа Коэна: согласие сверх того, что дало бы совпадение случайно.

    Взвешенный вариант (квадратичные веса) нужен потому, что оценки
    упорядочены: расхождение «2 против 0» хуже, чем «2 против 1», а простая
    каппа считает их одинаковыми промахами.
    """
    if len(a) != len(b):
        raise ValueError("списки оценок разной длины")
    if not a:
        raise ValueError("пустая выборка")
    labels = sorted(set(a) | set(b))
    n = len(a)
    ca, cb = Counter(a), Counter(b)

    def w(x: int, y: int) -> float:
        if not weighted:
            return 0.0 if x == y else 1.0
        span = (labels[-1] - labels[0]) or 1
        return ((x - y) / span) ** 2

    observed = sum(w(x, y) for x, y in zip(a, b)) / n
    expected = sum(w(x, y) * ca[x] * cb[y] for x in labels for y in labels) / (n * n)
    if expected == 0:
        return 1.0 if observed == 0 else 0.0
    return 1 - observed / expected


def kappa_verdict(k: float) -> str:
    """Словесная шкала Лэндиса и Коха — чтобы число не читали как проценты."""
    if k < 0.0:
        return "хуже случайного"
    if k < 0.20:
        return "ничтожное согласие"
    if k < 0.40:
        return "слабое согласие"
    if k < 0.60:
        return "умеренное согласие"
    if k < 0.80:
        return "существенное согласие"
    return "почти полное согласие"


def stratified_sample(items: Sequence[dict], key: str, size: int,
                      seed: int = 13) -> list[dict]:
    """Выборка, в которую попадают все оценки судьи, а не только нули.

    Доли берутся равными, а не пропорциональными: в пуле двоек единицы
    процента, и пропорциональная выборка в 150 пар дала бы две-три двойки —
    то есть ничего не сказала бы именно про те оценки, ради которых
    разметка и делается.
    """
    groups: dict[str, list[dict]] = {}
    for item in items:
        groups.setdefault(str(item[key]), []).append(item)
    rnd = random.Random(seed)
    out: list[dict] = []
    order = sorted(groups)
    share = max(1, size // max(1, len(order)))
    for name in order:
        pool = sorted(groups[name], key=lambda r: (r.get("query_id", ""),
                                                   r.get("chunk_id", "")))
        rnd.shuffle(pool)
        out += pool[:share]
    # если в какой-то оценке пар не хватило, добираем из самых многочисленных
    if len(out) < size:
        taken = {(r.get("query_id"), r.get("chunk_id")) for r in out}
        rest = [r for r in items if (r.get("query_id"), r.get("chunk_id")) not in taken]
        rnd.shuffle(rest)
        out += rest[:size - len(out)]
    return out[:size]
