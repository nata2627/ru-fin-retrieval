"""Удаление ссылок на нормативные акты из текста вопроса.

Зачем. Живые вопросы взяты из «Разъяснений» Банка России — это переписка
комплаенс-служб с регулятором, и в трёх четвертях таких вопросов автор сам
называет акт и пункт: «не применять п. 3.12 Положения № 590-П». Для поиска
это не вопрос, а адрес: номер акта совпадает с текстом фрагмента дословно,
и лексический поиск получает его даром. Чтобы понять, сколько качества
держится на номере, а сколько на смысле, нужно задать те же вопросы без
номеров и сравнить парно — на одних и тех же вопросах, а не на двух разных
подвыборках.

Два уровня, потому что «убрать номера» можно понять двояко.

`strip_numbers` убирает только сами обозначения, оставляя слова: «п. 3.12
Положения № 590-П» -> «п. Положения». Падежи после такой правки местами
не согласованы, зато правка минимальна и отвечает ровно на вопрос «что
будет, если номера в вопросе нет».

`strip_references` убирает ссылку целиком вместе со служебными словами:
«не применять п. 3.12 Положения № 590-П, который предусматривает» ->
«не применять , который предусматривает». Текст беднее, поэтому это оценка
снизу: часть падения на нём придётся не на потерю номера, а на рваную
формулировку.

Чего здесь сознательно нет. Номера, не относящиеся к актам, не трогаются:
в этих вопросах встречаются «процентная ставка № 1», «ставок № 1 и № 2»,
«0,01% от величины собственных средств». Поэтому номер удаляется либо
когда у него есть буквенный суффикс («590-П», «115-ФЗ», «5348-У»), либо
когда перед ним стоит слово, называющее акт. Отдельно стоящий «№ 1»
остаётся частью вопроса.
"""
from __future__ import annotations

import re

# Слова, называющие нормативный акт. Нужны, чтобы отличить номер акта
# от номера, который является частью вопроса.
ACT_WORD = (r"(?:положени|инструкци|указани|указ|постановлени|распоряжени|приказ|"
            r"письм|закон|федеральн\w*\s+закон|регламент|стандарт)\w*")
# Орган, который акт издал: «Банка России», «Правительства РФ».
ORGAN = r"(?:\s+(?:банка\s+россии|правительства(?:\s+рф)?|президента(?:\s+рф)?|цб(?:\s+рф)?))?"
# Дата акта: «от 27.03.2020».
DATE = r"(?:\s*,?\s*от\s+\d{1,2}\.\d{2}\.\d{4}(?:\s*г\.?)?)?"
# Номер акта с буквенным суффиксом: «590-П», «115-ФЗ», «ИН-08-23/42».
LETTERED = r"(?:\d+[-–][А-ЯA-Z]{1,3}|[А-Я]{2}-\d+-\d+/\d+)"
# Номер акта: либо с буквенным суффиксом, либо голые цифры после «№».
NUM = rf"(?:(?:№|N|No)\s*(?:{LETTERED}|\d+)|{LETTERED})"

# Акт целиком: слово-название, орган, дата, номер. Номер обязателен —
# «в соответствии с Положением» без номера ссылкой на конкретный акт
# не является и остаётся как есть.
ACT = re.compile(rf"({ACT_WORD}{ORGAN})({DATE}\s*{NUM})", re.I)
# Номер акта, оторванный от названия: «(далее — 590-П)».
ACT_TAIL = re.compile(rf"(?:(?:№|N|No)\s*)?{LETTERED}")

# Указатель внутрь акта и номер за ним, включая перечисления
# «п.п. 3.13 и 3.14», «пунктами 3.9.2, 3.14.1».
POINTER = (r"(?:п\.\s*п\.|пп\.|п\.|подп\.|абз\.|ст\.|гл\.|табл\.|прил\.|"
           r"пункт\w*|подпункт\w*|абзац\w*|стать\w+|глав\w+|таблиц\w+|приложени\w+)")
CLAUSE_NUM = r"\d+(?:\.\d+)*"
CLAUSE_LIST = rf"{CLAUSE_NUM}(?:\s*(?:,|и|или|-|–|—)\s*{CLAUSE_NUM})*"
CLAUSE = re.compile(rf"({POINTER})(\s*{CLAUSE_LIST})", re.I)
# Указатель вместе с номером — для полного удаления ссылки.
CLAUSE_FULL = re.compile(rf"{POINTER}\s*{CLAUSE_LIST}", re.I)


def has_act_number(text: str) -> bool:
    """Есть ли в вопросе номер акта. По этому признаку живые вопросы делятся
    на две группы: 108 с номером и 34 без."""
    return bool(ACT.search(text) or ACT_TAIL.search(text))


def strip_numbers(text: str) -> str:
    """Убрать обозначения, оставив слова: «п. 3.12 Положения № 590-П»
    -> «п. Положения»."""
    out = ACT.sub(lambda m: m.group(1), text)
    out = ACT_TAIL.sub("", out)
    out = CLAUSE.sub(lambda m: m.group(1), out)
    return tidy(out)


def strip_references(text: str) -> str:
    """Убрать ссылку целиком: «п. 3.12 Положения № 590-П» -> «»."""
    out = ACT.sub("", text)
    out = ACT_TAIL.sub("", out)
    out = CLAUSE_FULL.sub("", out)
    return tidy(out)


_SPACE = re.compile(r"[ \t]{2,}")
_BEFORE_PUNCT = re.compile(r"\s+([,.;:?!)»])")
_AFTER_OPEN = re.compile(r"([(«])\s+")
_EMPTY_BRACKETS = re.compile(r"\(\s*\)|«\s*»")
_DOUBLE_PUNCT = re.compile(r",(\s*,)+")
_DANGLING = re.compile(r"(?:\(\s*|«\s*)?(?:,\s*)?(?:и|или|с|в|по|на)?\s*$")


def tidy(text: str) -> str:
    """Убрать следы удаления: двойные пробелы, пробел перед запятой,
    пустые скобки. Текст после правки читается криво по падежам — это
    ожидаемо и в отчёте оговаривается; криво по пробелам он читаться
    не должен, иначе разница в метрике будет частично про разметку."""
    out = _EMPTY_BRACKETS.sub("", text)
    out = _DOUBLE_PUNCT.sub(",", out)
    out = _SPACE.sub(" ", out)
    out = _BEFORE_PUNCT.sub(r"\1", out)
    out = _AFTER_OPEN.sub(r"\1", out)
    out = _SPACE.sub(" ", out)
    return out.strip(" ,;")
