"""Разбор живых вопросов из «Разъяснений» Банка России.

Вопрос сам по себе бесполезен: чтобы он попал в тест, нужно знать, к какому
акту корпуса он относится. Банк России этого поля не отдаёт — акт приходится
восстанавливать из текста страницы. Здесь собрано всё, что для этого нужно,
одним местом: правило привязки, чистка номеров пунктов и устойчивая нумерация
запросов.

Почему отдельный модуль, а не функция в скрипте. Правило применяется трижды —
при сборке текстов запросов, при разметке по пунктам и при проверке сплита, —
и разойдись эти три применения, часть вопросов получила бы эталон из одного
акта, а метрику из другого.

## Откуда берётся номер акта

Три места на странице называют акт, и они не равноценны. Проверка простая:
если вопрос ссылается на пункт, а привязка верна, этот пункт должен
находиться в тексте названного акта. Доля попаданий по 1621 собранному
вопросу:

* **заголовок раздела** — 84% (127 вопросов с пунктами, пункт найден у 107);
* **текст самого вопроса** — 79% (102 вопроса, найден у 81);
* **тема блока** — проверить не на чем: после чистки от дат (см. ниже)
  ни у одного вопроса, где акт назван только в теме, номеров пунктов
  не осталось.

Поэтому порядок такой: заголовок раздела, затем текст вопроса, и ничего
больше. Тема блока не используется — не потому, что она плоха, а потому,
что доказательств её пригодности нет, а ошибка привязки тихо портит эталон.

## Почему из списка пунктов выкидываются даты

`collect_explanations.py` искал пункты выражением `\\d+(?:\\.\\d+)+`, и под
него попадает дата: «Указание Банка России от 09.12.2019 № 5348-У» даёт
«пункт» 09.12.2019. Из 745 собранных «пунктов» 218 оказались датами,
и у 193 вопросов список пунктов состоял из них целиком. Такой вопрос
выглядит как размечаемый автоматически, а на деле ищет в акте пункт
с номером 09.12.2019 и не находит ничего.

Выражение в сборщике исправлено, но перекачивать сайт ради этого не нужно:
собранное чинится чисткой при чтении. Оба места держат одно правило —
четырёхзначная часть означает год, а не номер пункта.
"""
from __future__ import annotations

import json
import re

# Номер акта: «590-П», «4892-У», «180-И», изредка «14/2-Т».
ACT_NUMBER = re.compile(r"\b(\d{1,4}(?:/\d+)?-[А-ЯЁ]{1,2})\b")
# Ссылка на пункт: «3.1.3», «3.7.2.2». Четырёхзначная часть — это год.
CLAUSE = re.compile(r"\b\d{1,3}(?:\.\d{1,3})+\b")

LIVE_PREFIX = "exp"
ORIGIN = "вопрос из разъяснений Банка России"


def clean_clauses(clauses: list[str]) -> list[str]:
    """Убрать из списка пунктов то, что на самом деле дата."""
    return [c for c in clauses if CLAUSE.fullmatch(c)]


def act_of(question: dict, corpus_numbers: set[str]) -> str | None:
    """Акт корпуса, к которому относится вопрос, или None.

    Порядок источников обоснован в шапке модуля: сначала заголовок раздела —
    это собственная привязка Банка России, потом номер, названный в самом
    вопросе. Возвращается первый номер, который в корпусе действительно есть:
    вопрос про закон или форму отчётности ответа в корпусе не имеет,
    и делать вид, что имеет, нельзя.
    """
    for number in question.get("acts", ()):
        if number in corpus_numbers:
            return number
    for number in ACT_NUMBER.findall(question.get("text", "")):
        if number in corpus_numbers:
            return number
    return None


def starts_clause(body: str, clause: str) -> bool:
    """Фрагмент начинает пункт: отдельная строка вида «3.1.3. ...».

    Проверка именно на начало строки, а не на вхождение: номер пункта
    встречается в перекрёстных ссылках («в соответствии с пунктом 3.1.3»)
    в десятках фрагментов, и по вхождению эталоном стал бы любой из них.
    """
    return re.search(r"(?:^|\n)\s*" + re.escape(clause) + r"\.\s", body) is not None


def body_of(chunk: dict) -> str:
    """Текст фрагмента без приписанной шапки акта."""
    text = chunk["text"]
    return text.split("\n\n", 1)[-1] if "\n\n" in text else text


def load_questions(path: str) -> list[dict]:
    """Прочитать собранные вопросы, почистив номера пунктов от дат."""
    out = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            q = json.loads(line)
            q["clauses"] = clean_clauses(q.get("clauses", []))
            out.append(q)
    return out


def assign_ids(texts: list[str], known: dict[str, str]) -> dict[str, str]:
    """Раздать вопросам устойчивые номера, не сдвинув уже выданные.

    Часть вопросов уже прошла через прогон и разметку под номерами вида
    `exp0007`. Пересчитать нумерацию с нуля значит оставить прежние оценки
    в `qrels.tsv` привязанными к чужим текстам — и заметить это по метрикам
    будет нельзя. Поэтому известные тексты сохраняют свои номера, а новые
    получают следующие свободные.
    """
    used = {int(qid[len(LIVE_PREFIX):]) for qid in known.values()
            if qid[len(LIVE_PREFIX):].isdigit()}
    nxt = max(used) + 1 if used else 0
    out: dict[str, str] = {}
    for text in texts:
        if text in known:
            out[text] = known[text]
            continue
        while nxt in used:
            nxt += 1
        out[text] = f"{LIVE_PREFIX}{nxt:04d}"
        used.add(nxt)
    return out
